export interface YearStats {
  year: string;
  yearNum: number;
  satCount: number;
  satAvg: number;
  satMax: number;
  satTiers: {
    top1400Plus: number;
    tier1300_1390: number;
    tier1200_1290: number;
    under1200: number;
  };
  ieltsCount: number;
  ieltsAvg: number;
  ieltsMax: number;
  ieltsTiers: {
    band8Plus: number;
    band7_5: number;
    band7_0: number;
    band6_5: number;
    band6_0: number;
  };
}

export const academicYearsList: ('2025-2026' | '2024-2025' | '2023-2024' | '2022-2023')[] = [
  '2025-2026',
  '2024-2025',
  '2023-2024',
  '2022-2023',
];

export function getYearlyStatistics(): YearStats[] {
  const years = ['2022-2023', '2023-2024', '2024-2025', '2025-2026'];
  return years.map((y) => {
    const yearCerts = certificatesData.filter((c) => c.academicYear === y);
    const satCerts = yearCerts.filter((c) => c.testType === 'SAT');
    const ieltsCerts = yearCerts.filter((c) => c.testType === 'IELTS');

    const satScores = satCerts.map((c) => c.score);
    const satAvg = satScores.length > 0 ? Math.round(satScores.reduce((a, b) => a + b, 0) / satScores.length) : 0;
    const satMax = satScores.length > 0 ? Math.max(...satScores) : 0;

    const satTiers = {
      top1400Plus: satCerts.filter((c) => c.score >= 1400).length,
      tier1300_1390: satCerts.filter((c) => c.score >= 1300 && c.score < 1400).length,
      tier1200_1290: satCerts.filter((c) => c.score >= 1200 && c.score < 1300).length,
      under1200: satCerts.filter((c) => c.score < 1200).length,
    };

    const ieltsScores = ieltsCerts.map((c) => c.score);
    const ieltsAvg = ieltsScores.length > 0 ? Number((ieltsScores.reduce((a, b) => a + b, 0) / ieltsScores.length).toFixed(1)) : 0;
    const ieltsMax = ieltsScores.length > 0 ? Math.max(...ieltsScores) : 0;

    const ieltsTiers = {
      band8Plus: ieltsCerts.filter((c) => c.score >= 8.0).length,
      band7_5: ieltsCerts.filter((c) => c.score === 7.5).length,
      band7_0: ieltsCerts.filter((c) => c.score === 7.0).length,
      band6_5: ieltsCerts.filter((c) => c.score === 6.5).length,
      band6_0: ieltsCerts.filter((c) => c.score <= 6.0).length,
    };

    const yearNum = parseInt(y.split('-')[1], 10);

    return {
      year: y,
      yearNum,
      satCount: satCerts.length,
      satAvg,
      satMax,
      satTiers,
      ieltsCount: ieltsCerts.length,
      ieltsAvg,
      ieltsMax,
      ieltsTiers,
    };
  });
}
